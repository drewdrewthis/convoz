// Generates src/schema.ts from packages/contracts/openapi.yaml (the source of truth).
//   node gen.mjs           write src/schema.ts
//   node gen.mjs --check   exit 1 when the committed file differs from what the contract generates (CI drift check)
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = import.meta.dirname;
const spec = path.join(here, "..", "contracts", "openapi.yaml");
const out = path.join(here, "src", "schema.ts");
const HEADER = "// Generated by packages/api-client/gen.mjs from packages/contracts/openapi.yaml. Do not edit; run `pnpm --filter @convoz/api-client gen`.\n\n";

const ast = await openapiTS(pathToFileURL(spec), { exportType: false });
const text = HEADER + astToString(ast);

if (process.argv.includes("--check")) {
  const committed = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
  if (committed !== text) {
    console.error("contract-drift: packages/api-client/src/schema.ts is out of date with packages/contracts. Run: pnpm --filter @convoz/api-client gen");
    process.exit(1);
  }
  console.log("contract-drift: packages/api-client/src/schema.ts matches packages/contracts");
} else {
  fs.writeFileSync(out, text);
  console.log(`api-client: wrote ${path.relative(process.cwd(), out)}`);
}
